export function getMockInvoices(): Invoice[] {
    return [...mockInvoices];
}

export function findMockInvoiceById(id: number): Invoice | undefined {
    return mockInvoices.find((invoice) => invoice.id === id);
}

export function findMockInvoiceByNumber(invoiceNumber: string): Invoice | undefined {
    return mockInvoices.find((invoice) => invoice.invoiceNumber === invoiceNumber);
}

export function findMockInvoiceByReservationId(
    reservationId: number
): Invoice | undefined {
    return mockInvoices.find((invoice) => invoice.reservationId === reservationId);
}

export function getMockInvoicesByClientId(clientId: number): Invoice[] {
    return mockInvoices.filter((invoice) => invoice.clientId === clientId);
}

export function filterMockInvoices(params: InvoiceSearchParams): Invoice[] {
    return mockInvoices.filter((invoice) => {
        const matchesNumber =
            !params.number ||
            invoice.invoiceNumber
                .toLowerCase()
                .includes(params.number.trim().toLowerCase());

        const matchesStatus =
            !params.status || invoice.status === params.status;

        const matchesClient =
            params.clientId === undefined || invoice.clientId === params.clientId;

        const matchesReservation =
            params.reservationId === undefined ||
            invoice.reservationId === params.reservationId;

        const invoiceDate = invoice.createdAt.slice(0, 10);

        const matchesFrom = !params.from || invoiceDate >= params.from;
        const matchesTo = !params.to || invoiceDate <= params.to;

        return (
            matchesNumber &&
            matchesStatus &&
            matchesClient &&
            matchesReservation &&
            matchesFrom &&
            matchesTo
        );
    });
}

export function calculateMockInvoiceStats(
    invoices: Invoice[] = mockInvoices
): InvoiceStats {
    return {
        total: invoices.length,
        draft: invoices.filter((invoice) => invoice.status === "DRAFT").length,
        issued: invoices.filter((invoice) => invoice.status === "ISSUED").length,
        paid: invoices.filter((invoice) => invoice.status === "PAID").length,
        cancelled: invoices.filter((invoice) => invoice.status === "CANCELLED").length,
        refunded: invoices.filter((invoice) => invoice.status === "REFUNDED").length,
        totalRevenue: invoices
            .filter((invoice) => invoice.status === "PAID")
            .reduce((sum, invoice) => sum + invoice.totalAmount, 0),
        pendingAmount: invoices
            .filter((invoice) => invoice.status === "ISSUED")
            .reduce((sum, invoice) => sum + invoice.totalAmount, 0),
        refundedAmount: invoices
            .filter((invoice) => invoice.status === "REFUNDED")
            .reduce((sum, invoice) => sum + invoice.totalAmount, 0),
    };
}
